#!/bin/sh
# Publish a GitHub release with the four assets the setup scripts download:
#   setup-codex.sh  setup-codex.ps1  config/config.toml  config/alp-cf-models.json
#
# Usage: scripts/release.sh [options] vX.Y.Z

set -e

ASSETS="setup-codex.sh setup-codex.ps1 config/config.toml config/alp-cf-models.json"
BRANCH="main"
DRY_RUN=0
VERSION=""
NOTES=""

say()  { printf '%s\n' "$*"; }
err()  { printf 'error: %s\n' "$*" >&2; }

have() { command -v "$1" >/dev/null 2>&1; }

usage() {
	cat <<'USAGE'
Usage: release.sh [options] vX.Y.Z

Validates the config, then tags HEAD of main as vX.Y.Z and publishes a GitHub
release with setup-codex.sh, setup-codex.ps1, config/config.toml and
config/alp-cf-models.json as assets.

Options:
  -h, --help          Show this help and exit.
  -n, --dry-run       Run all checks and print what would be released.
  --notes TEXT        Release notes. Default: notes generated by GitHub from
                      the commits since the previous release.
USAGE
}

while [ "$#" -gt 0 ]; do
	case "$1" in
		-h|--help) usage; exit 0 ;;
		-n|--dry-run) DRY_RUN=1 ;;
		--notes) [ "$#" -ge 2 ] || { err "--notes needs a value"; exit 2; }; NOTES="$2"; shift ;;
		-*) err "unknown option: $1"; usage >&2; exit 2 ;;
		*) [ -z "$VERSION" ] || { err "only one version allowed"; exit 2; }; VERSION="$1" ;;
	esac
	shift
done

is_semver() { printf '%s\n' "$1" | grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$'; }

# True if vX.Y.Z $1 is strictly greater than vX.Y.Z $2.
semver_gt() {
	printf '%s %s\n' "$1" "$2" | tr -d v | awk '{
		split($1, a, "."); split($2, b, ".")
		for (i = 1; i <= 3; i++) {
			if (a[i] + 0 > b[i] + 0) exit 0
			if (a[i] + 0 < b[i] + 0) exit 1
		}
		exit 1
	}'
}

[ -n "$VERSION" ] || { err "a version tag is required, e.g. v1.0.0"; usage >&2; exit 2; }
is_semver "$VERSION" || { err "version must look like vX.Y.Z, got: $VERSION"; exit 2; }

cd "$(dirname "$0")/.."

# --- Tools -------------------------------------------------------------------
for tool in git gh python3; do
	have "$tool" || { err "$tool is required."; exit 1; }
done
# tomllib is Python 3.11+; macOS's /usr/bin/python3 is 3.9.
python3 -c 'import tomllib' 2>/dev/null \
	|| { err "python3 is $(python3 -V 2>&1 | cut -d' ' -f2); 3.11+ is needed to validate config.toml."; exit 1; }
gh auth status >/dev/null 2>&1 || { err "gh is not logged in; run: gh auth login"; exit 1; }

# --- Repo state --------------------------------------------------------------
current=$(git rev-parse --abbrev-ref HEAD)
[ "$current" = "$BRANCH" ] || { err "on branch '$current'; releases are cut from '$BRANCH'."; exit 1; }

if [ -n "$(git status --porcelain)" ]; then
	err "working tree is not clean; commit or stash first."
	exit 1
fi

git fetch --quiet --tags origin "$BRANCH"
local_sha=$(git rev-parse HEAD)
remote_sha=$(git rev-parse "origin/$BRANCH")
if [ "$local_sha" != "$remote_sha" ]; then
	err "local $BRANCH ($local_sha) differs from origin/$BRANCH ($remote_sha); push or pull first."
	exit 1
fi

# --- Version -----------------------------------------------------------------
if git rev-parse -q --verify "refs/tags/$VERSION" >/dev/null; then
	err "tag $VERSION already exists."
	exit 1
fi

# GitHub marks a new release as latest, and the setup scripts download from
# releases/latest, so an older version would roll every new install back.
newest=$(git tag -l 'v*' --sort=-v:refname | while read -r t; do
	is_semver "$t" && { printf '%s\n' "$t"; break; }
done)
if [ -n "$newest" ] && ! semver_gt "$VERSION" "$newest"; then
	err "$VERSION is not newer than the latest tag, $newest."
	exit 1
fi

# --- Validate assets ---------------------------------------------------------
for f in $ASSETS; do
	[ -f "$f" ] || { err "missing asset: $f"; exit 1; }
done

python3 -m json.tool config/alp-cf-models.json >/dev/null \
	|| { err "config/alp-cf-models.json is not valid JSON."; exit 1; }
python3 -c 'import sys, tomllib; tomllib.load(open(sys.argv[1], "rb"))' config/config.toml \
	|| { err "config/config.toml is not valid TOML."; exit 1; }
sh -n setup-codex.sh || { err "setup-codex.sh has a syntax error."; exit 1; }

# The scripts must download from this repo's releases, or users get 404s.
repo=$(gh repo view --json nameWithOwner -q .nameWithOwner)
for f in setup-codex.sh setup-codex.ps1; do
	grep -q "github.com/$repo/releases/latest/download" "$f" \
		|| { err "$f does not download from github.com/$repo/releases; fix its release URL."; exit 1; }
done

# --- Publish -----------------------------------------------------------------
say "Releasing $VERSION from $BRANCH @ $(git rev-parse --short HEAD) to $repo"
say "Assets: $ASSETS"

if [ "$DRY_RUN" -eq 1 ]; then
	say "Dry run; nothing published."
	exit 0
fi

if [ -n "$NOTES" ]; then
	set -- --notes "$NOTES"
else
	set -- --generate-notes
fi

# shellcheck disable=SC2086
gh release create "$VERSION" --target "$local_sha" --title "$VERSION" "$@" $ASSETS

say "Published: https://github.com/$repo/releases/tag/$VERSION"
